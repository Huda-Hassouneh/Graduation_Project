#!/usr/bin/env python3
"""Validate config/aircraft/dji_matrice_400.yaml and export the flat JSON parameter database.

Usage (from the repository root):
    python3 scripts/export_m400_spec.py            # writes the JSON database and the generated parameter table
    python3 scripts/export_m400_spec.py --check    # exit 1 if either output is stale or the YAML is invalid

Outputs: config/aircraft/dji_matrice_400_parameters.json and docs/DJI_MATRICE_400_PARAMETER_TABLE.md.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from graduation_project.aircraft_spec import category_counts, export_parameters_json, iter_parameters, load_spec  # noqa: E402

OUT = REPO / "config" / "aircraft" / "dji_matrice_400_parameters.json"
TABLE = REPO / "docs" / "DJI_MATRICE_400_PARAMETER_TABLE.md"


def _fmt(v) -> str:
    if v is None:
        return "—"
    if isinstance(v, list):
        return "[" + ", ".join(_fmt(x) for x in v) + "]"
    return str(v).replace("|", "/")


def parameter_table(spec: dict) -> str:
    counts = category_counts(spec)
    lines = ["# DJI Matrice 400 — parameter table (GENERATED)", "",
             "Generated by `python3 scripts/export_m400_spec.py` from `config/aircraft/dji_matrice_400.yaml`. Do not edit.",
             "Narrative, interpretation and limitations: [DJI_MATRICE_400_TECHNICAL_SPECIFICATION.md]"
             "(DJI_MATRICE_400_TECHNICAL_SPECIFICATION.md). Sources: [DJI_MATRICE_400_SOURCE_REGISTER.md]"
             "(DJI_MATRICE_400_SOURCE_REGISTER.md).", "",
             "| category | count |", "|---|---|"] + [f"| {k} | {v} |" for k, v in counts.items()] + [""]
    section = None
    for p in iter_parameters(spec):
        sec = p.path.split(".")[0].split("[")[0]
        if sec != section:
            section = sec
            lines += ["", f"## {sec}", "", "| parameter | value | units | category | confidence | sources | range | note / rationale |",
                      "|---|---|---|---|---|---|---|---|"]
        note = p.note or p.rationale or p.derivation or ""
        if p.simulation_value:
            note = (note + "; " if note else "") + f"simulation stand-in: `{p.simulation_value}`"
        lines.append(f"| `{p.path.split('.', 1)[1] if '.' in p.path else p.path}` | {_fmt(p.value)} | {p.units} | {p.category} | "
                     f"{p.confidence} | {', '.join(p.sources)} | {_fmt(list(p.range)) if p.range else ''} | {_fmt(note)} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    spec = load_spec("dji_matrice_400")  # raises on any provenance violation
    text, table = export_parameters_json(spec), parameter_table(spec)
    if args.check:
        ok = (OUT.is_file() and OUT.read_text(encoding="utf-8") == text
              and TABLE.is_file() and TABLE.read_text(encoding="utf-8") == table)
        print("parameter exports are current" if ok else f"STALE: run python3 {Path(__file__).relative_to(REPO)}")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    TABLE.write_text(table, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} and {TABLE.relative_to(REPO)}: {category_counts(spec)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
